-- Cola de solicitudes del panel de mantenimiento; Google Apps Script consulta y empuja los datos.
-- Sólo esquema privado programacion; no se modifican OT ni cierres previos.
CREATE TABLE IF NOT EXISTS programacion.google_sheet_sync_request_v2 (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  periodo date NOT NULL,
  estado text NOT NULL DEFAULT 'PENDIENTE'
      CHECK (estado IN ('PENDIENTE', 'COMPLETADA', 'ERROR')),
  solicitado_en timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  terminado_en timestamptz,
  sincronizacion_id bigint REFERENCES programacion.google_sheet_sync_run_v2(id),
  resumen jsonb NOT NULL DEFAULT '{}'::jsonb,
  error_resumido text
);

CREATE UNIQUE INDEX IF NOT EXISTS google_sheet_sync_request_v2_periodo_pendiente
 ON programacion.google_sheet_sync_request_v2(periodo) WHERE estado='PENDIENTE';

CREATE INDEX IF NOT EXISTS google_sheet_sync_request_v2_periodo_fecha
 ON programacion.google_sheet_sync_request_v2(periodo, solicitado_en DESC);

CREATE TABLE IF NOT EXISTS programacion.google_sheet_sync_agent_v2 (
  id smallint PRIMARY KEY DEFAULT 1 CHECK (id=1),
  ultimo_contacto timestamptz,
  ultimo_preflight timestamptz,
  preflight_periodo date,
  preflight_resumen jsonb NOT NULL DEFAULT '{}'::jsonb,
  actualizado_en timestamptz NOT NULL DEFAULT now()
);

INSERT INTO programacion.google_sheet_sync_agent_v2(id)
VALUES (1)
ON CONFLICT(id) DO NOTHING;
